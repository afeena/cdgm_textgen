from dataclasses import dataclass, field
from typing import Optional

from fairseq.dataclass import ChoiceEnum
from fairseq.models.transformer import TransformerConfig


@dataclass
class CCMLMTransformerConfig(TransformerConfig):
    target_embed_path: Optional[str] = field(
        default=None,
        metadata={"help": "path to target embeddings"},
    )
    kappa: ChoiceEnum(["norm", "norm2", "tau", "none"]) = field(
        default="none",
        metadata={"help": "the type of kappa to use"},
    )
    no_last_dec_layer_norm: bool = field(
        default=True,
        metadata={"help": "don't add an layernorm after the last decoder block"},
    )
    apply_bert_init: bool = field(
        default=False, metadata={"help": "use custom param initialization for BERT"}
    )
    # --- special arguments ---
    sg_length_pred: bool = field(
        default=False,
        metadata={
            "help": "stop gradients through length"
        }
    )
    pred_length_offset: bool = field(
        default=False,
        metadata={
            "help": "predict length offset"
        },
    )
    length_loss_factor: float = field(
        default=0.1,
        metadata={"help": "loss factor for length"},
    )
    ngram_predictor: int = field(
        default=1, metadata={"help": "maximum iterations for iterative refinement."},
    )
    src_embedding_copy: bool = field(
        default=False,
        metadata={
            "help": "copy source embeddings"
        },
    )
